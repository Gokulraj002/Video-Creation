/** Deterministically cycles through a non-empty list. */
export function cycle<T>(items: NonEmpty<T>, index: number): T {
  return items[((index % items.length) + items.length) % items.length] ?? items[0];
}

/**
 * Genre-appropriate motion2d template used when the chosen engine is unavailable:
 * `title-card` for the first scene, `cta-end-card` for the last when a CTA exists, else the genre default.
 */
