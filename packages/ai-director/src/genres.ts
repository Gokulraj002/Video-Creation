type NonEmpty<T> = readonly [T, ...T[]];

/** Motion2D templates only (used for engine-fallback coercion). */
export type Motion2DTemplateId = Exclude<CatalogTemplateId, 'product-turntable' | 'logo-reveal-3d' | 'floating-shapes'>;

/** Creative defaults per genre: guidance for prompts, the heuristic mock, coercion and the compiler. */
export interface GenreProfile {
  genre: VideoGenre;
  label: string;
  /** Pacing guidance (shown to the model). */
  pacing: string;
  tone: NonEmpty<string>;
  audience: string;
  /** Objective template; `{title}` is replaced by the video title. */
  objective: string;
  visualDescription: string;
  typography: string;
  motionLanguage: string;
  /** Default palette (hex), used when the request has no brand colors. */
  palette: NonEmpty<string>;
  /** Body-scene templates in priority order; the first is the genre's hero template. */
  bodyTemplates: NonEmpty<CatalogTemplateId>;
  openingTemplate: CatalogTemplateId;
  /** Final-scene template when there is no call to action. */
  closingTemplate: CatalogTemplateId;
  /** Genre-appropriate motion2d template for engine coercion. */
  fallbackTemplate: Motion2DTemplateId;
  shotTypes: NonEmpty<ShotType>;
  cameraMovements: NonEmpty<CameraMovement>;
  transitions: NonEmpty<TransitionType>;
  moods: NonEmpty<string>;
  /** Narrative beats cycled through the body of the video. */
  beats: NonEmpty<string>;
  /** Chapter title seeds for multi-chapter videos. */
  chapterThemes: NonEmpty<string>;
  defaultCallToAction: string | null;
  threeEnvironment: ThreeEnvironment;
  threeLighting: ThreeLighting;
  captionPreset: CaptionStylePreset;
  /** Narration pace (words per second). */
  wordsPerSecond: number;
  /** Extra creative direction for the model. */
  guidance: string;
}

